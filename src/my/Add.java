    private void a_uKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_a_uKeyReleased
       db_conn dd=new db_conn();
        try{
           dd.query="select * from admin where username=?";
           dd.a.add(a_u.getText());
           ResultSet rs=dd.select();
           if(rs.next())
           {
              v.setText("Please enter diffrent id"); 
           }
           else{
               v.setText(""); 
           }
       }
       catch(NullPointerException e)
       {
           JOptionPane.showMessageDialog(null,"Database Connection Ereor");
       }
       catch(SQLException e)
       {
           JOptionPane.showMessageDialog(null,""+dd.error());
       }    
    }//GEN-LAST:event_a_uKeyReleased

