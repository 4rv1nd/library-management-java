    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
         db_conn dd=new db_conn(); 
        if(b.getText().equals("")){
            JOptionPane.showMessageDialog(null,"Please Enter Book name","Error",JOptionPane.INFORMATION_MESSAGE);
        }
        else if(a.getText().equals("")){
            JOptionPane.showMessageDialog(null,"Please Enter author name","Error",JOptionPane.INFORMATION_MESSAGE);
        }
        else{
            dd.query="delete from books where name=? and author=?";
            dd.a.add(a.getText());
            dd.a.add(b.getText());
            if(dd.update()){
                JOptionPane.showMessageDialog(null,"Done"," Sucsessfully Add",JOptionPane.INFORMATION_MESSAGE);
                this.dispose();
                new book_op().setVisible(true);
            } 
            else{
                JOptionPane.showMessageDialog(null,""+dd.error(),"ERROR",JOptionPane.ERROR_MESSAGE);
            }
            if(!dd.close()){
                JOptionPane.showMessageDialog(null,"Connection Error"," Error",JOptionPane.INFORMATION_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void bKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_bKeyReleased
       db_conn dd=new db_conn();
        DefaultTableModel dtm =(DefaultTableModel) t.getModel();
        if(b.getText().equals("") && a.getText().equals("")){
           dtm.setRowCount(0);
       }
       else{
            try{
                dd.query="select * from books where name LIKE '"+b.getText()+"%'";
                ResultSet rs=dd.select();
                dtm.setRowCount(0);
                while(rs.next()){
                    if(rs.getString("name").equals("Select Book") && rs.getString("author").equals("Select Author")){
                        
                    }
                    else{
                        dtm.addRow(new Object[]{rs.getString("name"),rs.getString("author")});
                    }
                }
       }
       catch(NullPointerException e){
           JOptionPane.showMessageDialog(null,"Connection Error");
       }
       catch(SQLException e){
           System.out.println(e);
       }
       if(!dd.close()){
                JOptionPane.showMessageDialog(null,"Connection Error"," Error",JOptionPane.INFORMATION_MESSAGE);
       }     
       }
    }//GEN-LAST:event_bKeyReleased

